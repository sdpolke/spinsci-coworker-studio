"""Exotel telephony provider package."""

import secrets
from typing import Any, Dict

from loguru import logger

from api.services.telephony.registry import (
    ProviderSpec,
    ProviderUIField,
    ProviderUIMetadata,
    ProviderUIOption,
    register,
)

from .config import (
    EXOTEL_SUBDOMAIN_MUMBAI,
    EXOTEL_SUBDOMAIN_SINGAPORE,
    ExotelConfigurationRequest,
    ExotelConfigurationResponse,
)
from .provider import EXOTEL_STREAM_SAMPLE_RATE, ExotelProvider
from .transport import create_transport


def _config_loader(value: Dict[str, Any]) -> Dict[str, Any]:
    return {
        "provider": "exotel",
        "api_key": value.get("api_key"),
        "api_token": value.get("api_token"),
        "account_sid": value.get("account_sid"),
        "subdomain": value.get("subdomain") or EXOTEL_SUBDOMAIN_MUMBAI,
        "inbound_secret": value.get("inbound_secret"),
        "from_numbers": value.get("from_numbers", []),
    }


async def _ensure_inbound_secret(credentials: Dict[str, Any]) -> Dict[str, Any]:
    """Mint an inbound token when the operator didn't supply one.

    Exotel does not sign App Bazaar callbacks, so this token — carried as a
    custom parameter on the Voicebot applet URL and on the outbound
    StatusCallback URL — is the only thing standing between a guessable
    endpoint and forged inbound calls or call outcomes. Generating it on save
    means every configuration created through the normal path is authenticated
    without the operator having to think about it.
    """
    if credentials.get("inbound_secret"):
        return credentials

    logger.info("[Exotel] generating inbound callback token for new configuration")
    return {**credentials, "inbound_secret": secrets.token_urlsafe(32)}


_UI_METADATA = ProviderUIMetadata(
    display_name="Exotel",
    docs_url="https://docs.exotel.com/exotel-agentstream/connect-voice-ai-api",
    fields=[
        ProviderUIField(
            name="api_key",
            label="API Key",
            type="password",
            sensitive=True,
            description="Exotel API Key (Dashboard → API Settings → API Credentials)",
        ),
        ProviderUIField(
            name="api_token",
            label="API Token",
            type="password",
            sensitive=True,
            description="Exotel API Token",
        ),
        ProviderUIField(
            name="account_sid",
            label="Account SID",
            type="text",
            sensitive=True,
            description="Exotel Account SID, e.g. mycompany1a",
        ),
        ProviderUIField(
            name="subdomain",
            label="Data Centre",
            type="select",
            required=True,
            placeholder=EXOTEL_SUBDOMAIN_MUMBAI,
            description="Exotel API host for the data centre your account lives in",
            options=[
                ProviderUIOption(value=EXOTEL_SUBDOMAIN_MUMBAI, label="Mumbai (India)"),
                ProviderUIOption(value=EXOTEL_SUBDOMAIN_SINGAPORE, label="Singapore"),
            ],
        ),
        # Deliberately not marked sensitive. Unlike the API credentials — which
        # the operator already holds from the Exotel dashboard — this value is
        # generated by us and has to be read back out to be pasted onto the
        # Voicebot applet URL in App Bazaar. Masking it would make it unusable.
        ProviderUIField(
            name="inbound_secret",
            label="Inbound Callback Token",
            type="text",
            required=False,
            sensitive=False,
            description=(
                "Token appended to the Voicebot applet URL as ?token=… to "
                "authenticate inbound calls. Generated automatically if left blank."
            ),
        ),
        ProviderUIField(
            name="from_numbers",
            label="Phone Numbers",
            type="string-array",
            description="ExoPhone numbers used as CallerId for outbound calls",
        ),
    ],
)


SPEC = ProviderSpec(
    name="exotel",
    provider_cls=ExotelProvider,
    config_loader=_config_loader,
    transport_factory=create_transport,
    transport_sample_rate=EXOTEL_STREAM_SAMPLE_RATE,
    config_request_cls=ExotelConfigurationRequest,
    config_response_cls=ExotelConfigurationResponse,
    ui_metadata=_UI_METADATA,
    account_id_credential_field="account_sid",
    preprocess_credentials_on_save=_ensure_inbound_secret,
)


register(SPEC)


